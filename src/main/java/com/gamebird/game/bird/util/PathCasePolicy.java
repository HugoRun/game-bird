package com.gamebird.game.bird.util;

/**
 * 路径片段的大小写策略。
 *
 * <p><b>为什么需要三档而不是「统一一种」</b>：大小写规则在不同用途下答案相反。
 * 目录名统一小写是为了跨平台一致（见 {@link #DIRECTORY_LOWERED}），
 * 而 {@code README.md}、{@code Dockerfile} 这类文件名强制改小写会造成
 * 大量无谓差异并破坏工具链兼容（见 {@link #PRESERVE}）。一刀切必然在某个用途上出错。
 *
 * <p><b>三档共同的不变式</b>：无论选哪一档，<b>分隔符一律统一为正斜杠 {@code /}</b>，
 * 冗余片段一律消解，越界 {@code ..} 一律抛错。大小写是唯一可变的维度。
 */
public enum PathCasePolicy {

    /**
     * 目录段转小写，文件基名保留原大小写，仅扩展名转小写。<b>本项目默认策略。</b>
     *
     * <p><b>为什么目录必须小写</b>：Windows 与 macOS 默认文件系统大小写不敏感，
     * Linux 默认敏感。于是 {@code GameData} 与 {@code gamedata} 在 Linux 上是两个
     * 不同目录、在 Windows 上是同一个目录 —— 同一份代码换台机器行为就变了。
     * 统一小写是唯一能让三平台行为一致的选择。
     *
     * <p><b>为什么文件基名保留大小写</b>：{@code README.md}、{@code Dockerfile}、
     * {@code pom.xml} 是约定俗成的名字，强行小写会产生大量无谓 diff，且部分工具链
     * 对大小写敏感，可能直接失效。
     *
     * <p><b>为什么扩展名仍转小写</b>：{@code .PNG} 与 {@code .png} 同样存在跨平台不一致，
     * 且 HTML/CSS 里引用时大小写混用极易出错—— 扩展名统一没有兼容性代价。
     */
    DIRECTORY_LOWERED,

    /**
     * 目录、文件基名、扩展名<b>全部</b>转小写。
     *
     * <p><b>适用场景</b>：需要「确定性别名」的地方——例如把用户输入的账号名、
     * 标签 key、大小写不敏感的资源标识符映射到文件系统路径时。若两个本应等价的
     * 输入被映射到不同文件，就会漏掉本该命中的缓存或资源。
     *
     * <p><b>不适用场景</b>：存放真实文件名的目录（如 {@code assets/}）。把
     * {@code Logo.PNG} 变成 {@code logo.png} 会让磁盘上的文件与代码不一致。
     */
    FULL_LOWERED,

    /**
     * 完全不动大小写，只做分隔符统一与冗余片段消解。
     *
     * <p><b>适用场景</b>：<b>已有</b>目录结构的读写——路径由外部系统给出
     * （配置文件、命令行参数、上游服务返回的路径），改名会直接找不到文件。
     * 此时规范化的目的只是消除分隔符差异与冗余片段，不应重命名任何东西。
     *
     * <p>注意：此策略下大小写不一致的路径<b>在 Linux 上仍可能找不到文件</b>。
     * 跨平台一致性由调用方自己保证，本工具不做保证。
     */
    PRESERVE
}
